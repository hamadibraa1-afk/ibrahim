@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>((localStorage.getItem('lang') as Lang) || 'ar');

  constructor() {
    effect(() => {
      const l = this.lang();
      localStorage.setItem('lang', l);
      document.documentElement.lang = l;
      document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
    });
  }

  t(key: string, ...args: (string | number)[]): string {
    const entry = D[key];
    let text = entry ? entry[this.lang() === 'ar' ? 0 : 1] : key;
    args.forEach((a, i) => (text = text.replace(`{${i}}`, String(a))));
    return text;
  }

  has(key: string): boolean { return key in D; }
  toggle(): void { this.lang.set(this.lang() === 'ar' ? 'en' : 'ar'); }
  pick(ar: string, en: string): string { return this.lang() === 'ar' ? ar : en; }
}

@Pipe({ name: 't', standalone: true, pure: false })
export class TPipe implements PipeTransform {
  private readonly i18n = inject(I18n);
  transform(key: string, ...args: (string | number)[]): string { return this.i18n.t(key, ...args); }
}
